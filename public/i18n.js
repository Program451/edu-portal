const I18N_LANG_NAMES = { ru: 'RU', en: 'EN', kk: 'KZ' };

function i18nGetLang() {
  return localStorage.getItem('appLang') || 'ru';
}

function i18nSetLang(lang) {
  if (!I18N_DICT[lang]) lang = 'ru';
  localStorage.setItem('appLang', lang);
  document.documentElement.lang = lang === 'kk' ? 'kk' : lang;
  i18nApply();
}

function i18nT(key) {
  const lang = i18nGetLang();
  return (I18N_DICT[lang] && I18N_DICT[lang][key]) || (I18N_DICT.ru[key]) || key;
}

function i18nApply() {
  const lang = i18nGetLang();
  const dict = I18N_DICT[lang] || I18N_DICT.ru;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) el.placeholder = dict[key];
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (dict[key]) el.title = dict[key];
  });

  document.dispatchEvent(new CustomEvent('i18n:changed', { detail: { lang } }));
}

// ─── Тёмная тема ───
function i18nGetTheme() {
  return localStorage.getItem('appTheme') || 'light';
}

function i18nSetTheme(theme) {
  theme = theme === 'dark' ? 'dark' : 'light';
  localStorage.setItem('appTheme', theme);
  document.documentElement.setAttribute('data-theme', theme);
  const btn = document.getElementById('appThemeBtn');
  if (btn) {
    btn.textContent = theme === 'dark' ? '☀️' : '🌙';
    btn.title = theme === 'dark' ? i18nT('controls.lightTheme') : i18nT('controls.darkTheme');
  }
}

function i18nToggleTheme() {
  i18nSetTheme(i18nGetTheme() === 'dark' ? 'light' : 'dark');
}

// ─── Виджет в правом верхнем углу (тема + язык) ───
function i18nInjectControls() {
  if (document.getElementById('appControls')) return;
  const wrap = document.createElement('div');
  wrap.className = 'app-controls';
  wrap.id = 'appControls';
  wrap.innerHTML = `
    <button class="app-controls-theme-btn" id="appThemeBtn" onclick="i18nToggleTheme()"></button>
    <select id="appLangSelect" onchange="i18nSetLang(this.value)" aria-label="Язык / Language / Тіл">
      <option value="ru">RU</option>
      <option value="en">EN</option>
      <option value="kk">KZ</option>
    </select>
  `;
  document.body.appendChild(wrap);
  document.getElementById('appLangSelect').value = i18nGetLang();
}

function i18nInit() {
  i18nSetTheme(i18nGetTheme());
  i18nInjectControls();
  i18nApply();
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', i18nInit);
} else {
  i18nInit();
}
