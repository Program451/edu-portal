'use strict';
// Вспомогательная функция для единообразной обработки ошибок в роутах: всегда
// логируем полный стек на сервере (в консоль/лог Render), а клиенту отвечаем
// то самое сообщение, что и было (многие сообщения ошибок в этом коде
// формируются клиенту осознанно понятными, поэтому они прокидываются как
// есть, а не технические, которые сюда попали случайно).
function sendServerError(res, e, publicMessage) {
  console.error('[server error]', e);
  res.status(500).json({ error: publicMessage || e.message });
}

module.exports = { sendServerError };
